"""Generate the SystemVerilog configuration header for a CA configuration and
convert frames to and from the $readmemh word format of the testbenches.

Example:
    python3 tools/gen_cfg.py --config configs/hodgepodge29.json --data-w 128 --out build/ca_cfg.svh
"""
import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "model"))

from ca_model import masks
from ca_model.rules import params_vector

BOUNDARY_ID = {"toroidal": 0, "cylindrical": 1, "rectangular": 2, "zero": 3}
RULE_ID = {"hodgepodge": 0, "ghm": 1, "interval": 2}


def gen_cfg_svh(cfg: dict, data_w: int, path) -> None:
    """Write localparams GRID_X, GRID_Y, CELL_W, NBH, BND_ID, RULE_ID, MASK,
    PARAMS and DATA_W (included inside a module body)."""
    n = cfg["nbh"]
    mask = masks.by_name(cfg["mask"], n)
    pv = params_vector(cfg["rule"], cfg["params"])
    params = "{" + ", ".join(f"32'd{v}" for v in reversed(pv)) + "}"
    text = (
        f"// Generated by tools/gen_cfg.py for configuration '{cfg.get('name', '')}'.\n"
        f"localparam int unsigned GRID_X  = {cfg['grid'][0]};\n"
        f"localparam int unsigned GRID_Y  = {cfg['grid'][1]};\n"
        f"localparam int unsigned CELL_W  = {cfg['cell_w']};\n"
        f"localparam int unsigned NBH     = {n};\n"
        f"localparam int unsigned BND_ID  = {BOUNDARY_ID[cfg['boundary']]};\n"
        f"localparam int unsigned RULE_ID = {RULE_ID[cfg['rule']]};\n"
        f"localparam logic [{n * n - 1}:0] MASK = {masks.to_sv_literal(mask)};\n"
        f"localparam ca_pkg::rule_params_t PARAMS = {params};\n"
        f"localparam int unsigned DATA_W  = {data_w};\n"
    )
    Path(path).write_text(text)


def frame_to_hex(grid: np.ndarray, cell_w: int, data_w: int) -> list[str]:
    """One DATA_W-bit hex word per line, row-major, first cell in the low bits."""
    per = data_w // cell_w
    digits = data_w // 4
    g = np.asarray(grid, dtype=np.int64)
    if g.min() < 0 or g.max() >= (1 << cell_w):
        raise ValueError(f"cell values outside 0..{(1 << cell_w) - 1}")
    out = []
    for row in g:
        for b in range(0, len(row), per):
            w = 0
            for k, c in enumerate(row[b:b + per]):
                w |= int(c) << (k * cell_w)
            out.append(f"{w:0{digits}x}")
    return out


def hex_to_frame(lines, grid_x: int, grid_y: int, cell_w: int, data_w: int) -> np.ndarray:
    per = data_w // cell_w
    mask = (1 << cell_w) - 1
    words = [int(t, 16) for t in lines]
    out = np.zeros((grid_y, grid_x), dtype=np.uint8)
    for y in range(grid_y):
        for x in range(grid_x):
            w = words[(y * grid_x + x) // per]
            out[y, x] = (w >> ((x % per) * cell_w)) & mask
    return out


def main(argv=None) -> int:
    from ca_model import config
    ap = argparse.ArgumentParser(description="Write ca_cfg.svh for a configuration file")
    ap.add_argument("--config", required=True)
    ap.add_argument("--data-w", type=int, default=128)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    gen_cfg_svh(config.load(args.config), args.data_w, args.out)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
